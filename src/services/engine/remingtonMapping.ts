const KEY_MAP = new Map<string, RemingtonKeyDef>();
REMINGTON_KEYS.forEach((k) => KEY_MAP.set(k.code, k));

const ALT_CODE_MAP = new Map<string, string>();
REMINGTON_ALT_CODES.forEach((a) => ALT_CODE_MAP.set(a.code, a.character));

/**
 * Maps physical keyboard event.code to Hindi Remington character based on shift modifier.
 */
export function mapPhysicalKeyToRemington(code: string, isShift: boolean): string | null {
  const def = KEY_MAP.get(code);
  if (!def) return null;
  return isShift ? def.hiShift : def.hiNormal;
}

/**
 * Resolves a 4-digit typewriter Alt code to its Unicode Hindi character.
 */
export function resolveAltCodeCharacter(code: string): string | null {
  return ALT_CODE_MAP.get(code) || null;
}

/**
 * Converts Remington typewriter keystroke order into standard Devanagari Unicode.
 * On traditional Remington typewriters:
 * KeyF ('ि' / Chhoti Ee matra) is typed BEFORE the consonant (e.g. typing 'ि' then 'क' produces 'कि').
 * In Unicode, the consonant comes first, then the matra ('क' + 'ि' = 'कि').
 */
export function convertTypewriterOrderToUnicode(rawTyped: string): string {
  if (!rawTyped || !rawTyped.includes('ि')) return rawTyped;

  // Regex to swap leading 'ि' followed by consonant
  // e.g. "ि" + consonant -> consonant + "ि"
  return rawTyped.replace(/ि([क-ह])/g, '$1ि');
}

